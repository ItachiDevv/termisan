def get_sprite(theme_id: str) -> str:
    """Get the ASCII art sprite for a given theme ID."""
    return SPRITES.get(theme_id, "")


def get_sprite_lines(theme_id: str) -> list[str]:
    """Get the sprite as a list of lines (without leading/trailing blank lines)."""
    sprite = get_sprite(theme_id)
    lines = sprite.split("\n")
    # Strip leading and trailing empty lines
    while lines and not lines[0].strip():
        lines.pop(0)
    while lines and not lines[-1].strip():
        lines.pop()
    return lines


def get_sprite_dimensions(theme_id: str) -> tuple[int, int]:
    """Get (height, max_width) of a sprite."""
    lines = get_sprite_lines(theme_id)
    if not lines:
        return (0, 0)
    max_width = max(len(line) for line in lines)
    return (len(lines), max_width)
